window.currentLang = localStorage.getItem('orderit_lang') || 'vi';

function setLang(lang) {
  window.currentLang = lang;
  localStorage.setItem('orderit_lang', lang);
  applyTranslations();
  window.dispatchEvent(new CustomEvent('lang-changed', { detail: { lang } }));
}

function t(key) {
  const dict = I18N[window.currentLang];
  return (dict && dict[key]) || key;
}

function applyTranslations() {
  document.documentElement.lang = window.currentLang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });
  
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.title = t(key);
  });

  document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
    btn.textContent = window.currentLang === 'vi' ? '🇻🇳 VI' : '🇬🇧 EN';
  });
}

window.t = t;
window.setLang = setLang;
window.applyTranslations = applyTranslations;

document.addEventListener('click', (e) => {
  if (e.target.closest && e.target.closest('.lang-toggle-btn')) {
    setLang(window.currentLang === 'vi' ? 'en' : 'vi');
  }
});

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', applyTranslations);
} else {
  applyTranslations();
}
